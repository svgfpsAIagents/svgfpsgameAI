/*
 * play_helios_frame.c
 *
 * Plays a JOY-SCAN laser frame (helios_frame.h) on a Helios Laser DAC.
 *
 * The Helios SDK is loaded at runtime via dlopen(), so this file compiles
 * standalone. At runtime you need libhelios_dac.so (Linux), helios_dac.dll
 * (Windows), or libhelios_dac.dylib (macOS) somewhere on your system.
 *
 * BUILD:
 *   Linux:   gcc -O2 -o play_helios_frame play_helios_frame.c -ldl
 *   macOS:   cc   -O2 -o play_helios_frame play_helios_frame.c -ldl
 *   Windows (MSYS2/MinGW): gcc -O2 -o play_helios_frame.exe play_helios_frame.c
 *
 * RUN:
 *   ./play_helios_frame                       # play frame once
 *   ./play_helios_frame --loop 60             # play 60 times (~2s at 30k pps, 1530 pts)
 *   ./play_helios_frame --loop 0              # infinite loop (Ctrl-C to stop)
 *   ./play_helios_frame --dry-run             # don't touch hardware, just verify the frame
 *   ./play_helios_frame --lib /path/libhelios_dac.so
 *   ./play_helios_frame --device 0            # pick DAC index (default 0)
 *
 * REQUIREMENTS AT RUNTIME (only when not --dry-run):
 *   - libhelios_dac.so/.dll/.dylib somewhere dlopen() can find it
 *     (LD_LIBRARY_PATH, /usr/local/lib, or pass --lib <path>)
 *   - A Helios Laser DAC connected via USB
 *   - Permission to access the USB device (udev rule or root on Linux)
 *
 * The frame itself is in helios_frame.h (generated by joy_scan_laser.svg,
 * "Laser DAC Export" -> "EXPORT .H"). Replace that file with your own export
 * to play a different frame.
 */

#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

#ifdef _WIN32
  #include <windows.h>
  #define SLEEP_MS(ms) Sleep(ms)
#else
  #include <unistd.h>
  #include <dlfcn.h>
  #define SLEEP_MS(ms) usleep((ms) * 1000)
#endif

#include "helios_frame.h"

/* ----- Helios SDK C API signatures (matched at runtime via dlopen) ----- */
typedef int  (*fn_HeliosDac_Initialize)(void);
typedef int  (*fn_HeliosDac_WriteFrame)(unsigned int devNum, unsigned int pps,
                                        unsigned char* frameData,
                                        unsigned int numOfPoints,
                                        unsigned int blankingShift);
typedef int  (*fn_HeliosDac_Stop)(unsigned int devNum);
typedef int  (*fn_HeliosDac_CloseDevices)(void);

static fn_HeliosDac_Initialize   p_Init  = NULL;
static fn_HeliosDac_WriteFrame   p_Write = NULL;
static fn_HeliosDac_Stop         p_Stop  = NULL;
static fn_HeliosDac_CloseDevices p_Close = NULL;

#ifdef _WIN32
static HMODULE g_lib = NULL;
#else
static void*   g_lib = NULL;
#endif

static int load_sdk(const char* user_path) {
    const char* candidates[] = {
        user_path,
        "libhelios_dac.so",
        "./libhelios_dac.so",
        "/usr/local/lib/libhelios_dac.so",
        "/usr/lib/libhelios_dac.so",
        "helios_dac.dll",
        "./helios_dac.dll",
        "libhelios_dac.dylib",
        "./libhelios_dac.dylib",
        NULL
    };
    for (int i = 0; candidates[i] != NULL; i++) {
        if (candidates[i] == NULL) continue;
#ifdef _WIN32
        g_lib = LoadLibraryA(candidates[i]);
        if (!g_lib) continue;
        p_Init  = (fn_HeliosDac_Initialize)  GetProcAddress(g_lib, "HeliosDac_Initialize");
        p_Write = (fn_HeliosDac_WriteFrame)  GetProcAddress(g_lib, "HeliosDac_WriteFrame");
        p_Stop  = (fn_HeliosDac_Stop)         GetProcAddress(g_lib, "HeliosDac_Stop");
        p_Close = (fn_HeliosDac_CloseDevices) GetProcAddress(g_lib, "HeliosDac_CloseDevices");
#else
        g_lib = dlopen(candidates[i], RTLD_NOW);
        if (!g_lib) continue;
        p_Init  = (fn_HeliosDac_Initialize)  dlsym(g_lib, "HeliosDac_Initialize");
        p_Write = (fn_HeliosDac_WriteFrame)  dlsym(g_lib, "HeliosDac_WriteFrame");
        p_Stop  = (fn_HeliosDac_Stop)         dlsym(g_lib, "HeliosDac_Stop");
        p_Close = (fn_HeliosDac_CloseDevices) dlsym(g_lib, "HeliosDac_CloseDevices");
#endif
        if (p_Init && p_Write && p_Stop && p_Close) {
            fprintf(stderr, "[sdk] loaded %s\n", candidates[i]);
            return 0;
        }
#ifdef _WIN32
        FreeLibrary(g_lib); g_lib = NULL;
#else
        dlclose(g_lib); g_lib = NULL;
#endif
    }
    return -1;
}

static void usage(const char* prog) {
    printf("Usage: %s [options]\n", prog);
    printf("  --loop N       play N times (0 = infinite, Ctrl-C to stop)\n");
    printf("  --dry-run      verify frame only, no hardware access\n");
    printf("  --lib PATH     path to libhelios_dac.so/.dll/.dylib\n");
    printf("  --device N     DAC index (default 0)\n");
    printf("  --help         this message\n");
    printf("\nFrame: %u points @ %u PPS, %zu bytes total\n",
           HELIOS_FRAME_POINT_COUNT, HELIOS_FRAME_PPS, sizeof(helios_frame));
}

int main(int argc, char** argv) {
    int loops = 1;
    int dry_run = 0;
    unsigned int device = 0;
    const char* lib_path = NULL;

    for (int i = 1; i < argc; i++) {
        if      (!strcmp(argv[i], "--loop")    && i+1 < argc) loops    = atoi(argv[++i]);
        else if (!strcmp(argv[i], "--device")  && i+1 < argc) device  = (unsigned)atoi(argv[++i]);
        else if (!strcmp(argv[i], "--lib")     && i+1 < argc) lib_path = argv[++i];
        else if (!strcmp(argv[i], "--dry-run")) dry_run = 1;
        else if (!strcmp(argv[i], "--help"))   { usage(argv[0]); return 0; }
        else { fprintf(stderr, "Unknown arg: %s (try --help)\n", argv[i]); return 1; }
    }

    /* ----- Frame sanity check ----- */
    printf("JOY-SCAN Helios Laser DAC player\n");
    printf("  device : %u\n", device);
    printf("  points : %u\n", HELIOS_FRAME_POINT_COUNT);
    printf("  pps    : %u\n", HELIOS_FRAME_PPS);
    printf("  size   : %zu bytes (%zu bytes/point)\n",
           sizeof(helios_frame), sizeof(HeliosPoint));

    /* Verify all X,Y are in 12-bit range and struct layout matches the SDK. */
    uint16_t xmin = 4095, xmax = 0, ymin = 4095, ymax = 0;
    for (uint32_t i = 0; i < HELIOS_FRAME_POINT_COUNT; i++) {
        uint16_t x = helios_frame[i].x, y = helios_frame[i].y;
        if (x < xmin) xmin = x;
        if (x > xmax) xmax = x;
        if (y < ymin) ymin = y;
        if (y > ymax) ymax = y;
    }
    printf("  x range: [%u, %u]   y range: [%u, %u]   (12-bit valid: 0..4095)\n",
           xmin, xmax, ymin, ymax);
    if (xmax > 4095 || ymax > 4095) {
        fprintf(stderr, "ERROR: frame coordinates exceed 12-bit range.\n");
        return 2;
    }
    if (sizeof(HeliosPoint) != 8) {
        fprintf(stderr, "ERROR: sizeof(HeliosPoint) = %zu, expected 8 (no padding).\n",
                sizeof(HeliosPoint));
        return 2;
    }

    if (dry_run) {
        printf("[DRY RUN] OK. Would call HeliosDac_WriteFrame(%u, %u, helios_frame, %u, 0).\n",
               device, HELIOS_FRAME_PPS, HELIOS_FRAME_POINT_COUNT);
        return 0;
    }

    /* ----- Load the SDK ----- */
    if (load_sdk(lib_path) != 0) {
        fprintf(stderr,
            "ERROR: could not load libhelios_dac.so/.dll/.dylib.\n"
            "       Pass --lib /path/to/libhelios_dac.so, or use --dry-run.\n");
        return 3;
    }

    /* ----- Open devices ----- */
    int n = p_Init();
    if (n <= 0) {
        fprintf(stderr, "ERROR: HeliosDac_Initialize returned %d (no DACs found).\n", n);
        return 4;
    }
    printf("  dacs   : %d found; using device %u.\n", n, device);

    /* ----- Frame duration in ms (so we don't queue faster than the DAC plays) ----- */
    unsigned int frame_ms = (HELIOS_FRAME_POINT_COUNT * 1000u) / HELIOS_FRAME_PPS;
    if (frame_ms == 0) frame_ms = 1;
    printf("  frame  : %u ms per playback at %u PPS\n", frame_ms, HELIOS_FRAME_PPS);
    printf("  loops  : %d%s\n", loops, loops == 0 ? " (infinite, Ctrl-C to stop)" : "");

    /* ----- Play ----- */
    int played = 0;
    while (loops == 0 || played < loops) {
        int rc = p_Write(device, HELIOS_FRAME_PPS,
                         (unsigned char*)helios_frame,
                         HELIOS_FRAME_POINT_COUNT, 0);
        if (rc != 1) {
            fprintf(stderr, "ERROR: WriteFrame returned %d at loop %d\n", rc, played);
            p_Stop(device);
            p_Close();
            return 5;
        }
        played++;
        SLEEP_MS(frame_ms);
    }

    /* ----- Cleanup ----- */
    p_Stop(device);
    p_Close();
    printf("Done. Played %d frames.\n", played);
    return 0;
}
